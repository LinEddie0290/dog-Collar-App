/// Self-verifying test of the PET v1 protocol implementation.
///
/// Every expected byte string below was produced by the firmware repo's own
/// reference implementation (`PET-main/tools/pet_codec.py`) and, for the
/// GET_CONFIG case, matches the worked example in section 4.3 of the
/// integration manual byte for byte. So this is a real cross-check against the
/// firmware side, not a test of our code against itself.
///
/// Runs with a bare `dart` SDK — no BLE hardware, no Flutter, no pub get.
library;

import 'dart:typed_data';

import 'package:collar_data/collar_data.dart';

int _checks = 0;
int _failures = 0;

void check(String what, bool ok, [String detail = '']) {
  _checks++;
  if (ok) {
    print('  ok   $what');
  } else {
    _failures++;
    print('  FAIL $what${detail.isEmpty ? '' : ' — $detail'}');
  }
}

void checkEq(String what, Object? actual, Object? expected) =>
    check(what, actual == expected, 'got $actual, want $expected');

void checkClose(String what, double actual, double expected,
        [double tol = 1e-9]) =>
    check(what, (actual - expected).abs() < tol,
        'got $actual, want $expected');

void checkThrows(String what, void Function() body) {
  try {
    body();
    check(what, false, 'expected a PetProtocolException, none thrown');
  } on PetProtocolException {
    check(what, true);
  } catch (e) {
    check(what, false, 'wrong exception type: $e');
  }
}

/// Goldens from pet_codec.py. See the header note above.
class Golden {
  /// Manual section 4.3: GET_CONFIG, request_id 1.
  static const String getConfigFrame =
      '50540101000000000100000001000000000000000000000002';
  static const List<String> getConfigFragmentsMtu23 = <String>[
    'a501010019000000505401010000000001000000',
    'a501010019000c00010000000000000000000000',
    'a50101001900180002',
  ];

  /// SET_CONFIG turning the microphone off: mask 0x0f, rates [104,100,2,0,0].
  static const String setConfigMicOffFrame =
      '5054010100000000070000000f0000000000000000000000030f000000'
      '68006400020000000000';

  /// GPS sample carrying a valid fix near 31.2304 N, 121.4737 E.
  static const String gpsFixFrame =
      '505401032a000000640000004d00000015cd5b0700000000090000000400450024'
      '474e524d432c3038333535392e30302c412c333131332e383234302c4e2c313231'
      '32382e343232302c452c302e3030342c37372e35322c3039313232362c2c2c412a'
      '3444';

  /// GPS sample that is well-formed but reports NO fix — exactly the shape the
  /// collar produced during the 2026-09-11 bench test (quality 0, 0 sats).
  static const String gpsNoFixFrame =
      '505401032a000000640000003000000015cd5b0700000000090000000400280024'
      '47504747412c3038333535392e30302c2c2c2c2c302c30302c39392e39392c2c2c'
      '2c2c2c2a3634';

  /// Onboard IMU at rest: gravity on Z, near-zero gyro.
  static const String imuFrame =
      '505401032a000000640000002000000015cd5b070000000009000000010018'
      '00e02e0000c0e0ffffb0a09500e803000030f8fffff4010000';

  /// MLX90615: object 38.512 °C, ambient 25.375 °C.
  static const String tempFrame =
      '505401032a000000640000001000000015cd5b070000000009000000030008'
      '00709600001f630000';

  /// A failed temperature read, errno -5 (EIO).
  static const String readErrorFrame =
      '505401032a000000640000000c00000015cd5b0700000000090000000301'
      '0400fbffffff';

  /// GET_CONFIG response: streaming, mask 0x0f active, 3 frames dropped.
  static const String getConfigResponseFrame =
      '505401022a00000001000000280000002b0200000000000002000000090000000f'
      '00000068006400020000000000010003000000000000000f0000000f000000';

  /// The 20-byte Status Read snapshot (no frame header, no fragment header).
  static const String statusReadValue =
      '010107002a000000090000000f00000003000000';
}

void main() {
  print('PET v1 protocol self-test');
  print('(goldens generated by PET-main/tools/pet_codec.py)\n');

  print('1. コマンドのエンコード — 手引き 4.3 の例と一致するか');
  final Uint8List getConfig =
      encodeCommand(opcode: PetOpcode.getConfig, requestId: 1);
  checkEq('GET_CONFIG frame is 25 bytes', getConfig.length, 25);
  checkEq('GET_CONFIG bytes match the manual', petToHex(getConfig),
      Golden.getConfigFrame);

  final Uint8List setConfig = encodeCommand(
    opcode: PetOpcode.setConfig,
    requestId: 7,
    body: encodeConfig(mask: 0x0F, rates: <int>[104, 100, 2, 0, 0]),
  );
  checkEq('SET_CONFIG (mic off) bytes match the reference',
      petToHex(setConfig), Golden.setConfigMicOffFrame);

  print('\n2. 分割 — MTU 23 で3片に割れるか');
  final List<Uint8List> frags = fragmentFrame(getConfig, messageId: 1, mtu: 23);
  checkEq('fragment count', frags.length, 3);
  for (int i = 0; i < frags.length; i++) {
    checkEq('fragment $i', petToHex(frags[i]),
        Golden.getConfigFragmentsMtu23[i]);
  }

  print('\n3. 再組み立て — 分割したものが元に戻るか');
  final PetReassembler rx = PetReassembler();
  PetFrame? rebuilt;
  for (final Uint8List f in frags) {
    rebuilt = rx.feed(f) ?? rebuilt;
  }
  check('reassembled a frame', rebuilt != null);
  checkEq('reassembler is empty afterwards', rx.inProgress, false);
  if (rebuilt != null) {
    checkEq('kind', rebuilt.kind, PetKind.command);
    checkEq('request_id round-trips', rebuilt.sequence, 1);
    checkEq('opcode byte', rebuilt.payload[0], PetOpcode.getConfig.value);
  }

  print('\n4. 再組み立ての異常系 — 壊れた入力を弾くか');
  checkThrows('rejects a bad fragment magic', () {
    PetReassembler().feed(<int>[0xFF, 1, 0, 0, 25, 0, 0, 0, 0x50]);
  });
  checkThrows('rejects a non-contiguous offset', () {
    final PetReassembler r = PetReassembler();
    r.feed(frags[0]);
    r.feed(frags[2]); // skips the middle fragment
  });
  checkThrows('rejects an empty fragment', () {
    PetReassembler().feed(<int>[0xA5, 1, 0, 0, 25, 0, 0, 0]);
  });
  final PetReassembler r5 = PetReassembler();
  try {
    r5.feed(frags[0]);
    r5.feed(frags[2]);
  } on PetProtocolException {
    // ignored on purpose: the point is the state reset that follows
  }
  checkEq('reassembler resets itself after an error', r5.inProgress, false);

  print('\n5. GPS サンプル — 生の NMEA が取り出せるか');
  final PetSample gps = decodePetSample(decodeFrame(
      petFromHex(Golden.gpsFixFrame)));
  check('GPS decodes to PetGpsSample', gps is PetGpsSample);
  if (gps is PetGpsSample) {
    checkEq('sensor', gps.sensor, PetSensor.gps);
    checkEq('config_id', gps.configId, 9);
    check('sentence is RMC with status A',
        gps.sentence.startsWith(r'$GNRMC') && gps.sentence.contains(',A,'));
    print('       ${gps.sentence}');
  }
  final PetSample noFix = decodePetSample(decodeFrame(
      petFromHex(Golden.gpsNoFixFrame)));
  if (noFix is PetGpsSample) {
    check('no-fix sentence is still structurally valid',
        noFix.sentence.startsWith(r'$GPGGA'));
    print('       ${noFix.sentence}  ← 正しい文だが未測位');
  }

  print('\n6. IMU / 温度 / エラー サンプル');
  final PetSample imu =
      decodePetSample(decodeFrame(petFromHex(Golden.imuFrame)));
  check('IMU decodes to PetImuSample', imu is PetImuSample);
  if (imu is PetImuSample) {
    checkClose('ax m/s²', imu.ax, 0.012);
    checkClose('ay m/s²', imu.ay, -0.008);
    checkClose('az m/s² (gravity)', imu.az, 9.806);
    checkClose('gx rad/s', imu.gx, 0.001);
    check('magnitude is about 9.8 (gravity at rest)',
        (imu.accelMagnitude - 9.806).abs() < 0.01,
        'got ${imu.accelMagnitude}');
  }

  final PetSample temp =
      decodePetSample(decodeFrame(petFromHex(Golden.tempFrame)));
  check('temperature decodes', temp is PetTemperatureSample);
  if (temp is PetTemperatureSample) {
    checkClose('object °C', temp.objectC, 38.512, 1e-6);
    checkClose('ambient °C', temp.ambientC, 25.375, 1e-6);
  }

  final PetSample err =
      decodePetSample(decodeFrame(petFromHex(Golden.readErrorFrame)));
  check('read error decodes', err is PetReadError);
  if (err is PetReadError) {
    checkEq('errno', err.errno, -5);
    checkEq('error names its sensor', err.sensor, PetSensor.mlx90615);
  }

  print('\n7. 応答フレームと Status Read');
  final PetResponse resp =
      decodeResponse(decodeFrame(petFromHex(Golden.getConfigResponseFrame)));
  checkEq('opcode', resp.opcode, PetOpcode.getConfig);
  checkEq('result', resp.result, PetResult.ok);
  checkEq('config_id', resp.configId, 9);
  check('body is a config/status', resp.body is PetConfigStatus);
  if (resp.body case final PetConfigStatus st) {
    checkEq('state', st.state, PetState.streaming);
    checkEq('dropped', st.dropped, 3);
    checkEq('mic is off in the running config', st.active(PetSensor.mic), false);
    checkEq('GPS is active', st.active(PetSensor.gps), true);
    checkEq('GPS rate is 0 (event driven, not disabled)',
        st.config.rateOf(PetSensor.gps), 0);
    checkEq('GPS is enabled by its mask bit',
        st.config.enabled(PetSensor.gps), true);
  }

  final PetStatusSnapshot snap =
      decodeStatusRead(petFromHex(Golden.statusReadValue));
  checkEq('boot_id', snap.bootId, 42);
  checkEq('state', snap.state, PetState.streaming);
  check('data subscribed', snap.dataSubscribed);
  check('status subscribed', snap.statusSubscribed);
  check('connected', snap.connected);
  checkEq('not time-synced yet', snap.timeSynced, false);
  checkThrows('Status Read must not be fed to the reassembler',
      () => PetReassembler().feed(petFromHex(Golden.statusReadValue)));

  print('\n8. 設定の妥当性検査');
  checkThrows('a disabled sensor must have rate 0',
      () => encodeConfig(mask: 0x03, rates: <int>[104, 100, 2, 0, 0]));
  checkThrows('mask bits above 0x1f are rejected',
      () => encodeConfig(mask: 0x20, rates: <int>[0, 0, 0, 0, 0]));
  checkThrows('exactly five rates are required',
      () => encodeConfig(mask: 0x01, rates: <int>[104]));
  final Uint8List ok =
      encodeConfig(mask: petDefaultMask, rates: petDefaultRates);
  checkEq('power-on default config encodes to 14 bytes', ok.length, 14);

  print('\n${'=' * 52}');
  if (_failures == 0) {
    print('全 $_checks 件 通過 — PET v1 の実装は firmware 側の');
    print('リファレンス実装とバイト単位で一致しています。');
  } else {
    print('$_checks 件中 $_failures 件 失敗');
  }
  print('=' * 52);
}
