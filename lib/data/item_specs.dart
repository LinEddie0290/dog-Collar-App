library;

class ItemSpec {
  const ItemSpec(
    this.id, {
    required this.unit,
    required this.min,
    required this.max,
    this.decimals = 0,
    required this.what,
    required this.why,
    required this.source,
    this.link = false,
  });

  final String id;

  /// 値の単位（例：分钟）。[link] なら使わない。
  final String unit;

  /// 示例の値のふつうの範囲。
  final double min;
  final double max;
  final int decimals;

  /// 何を見ているか。
  final String what;

  /// なぜ大事か。
  final String why;

  /// データの出どころ（センサー → 計算）。
  final String source;

  /// 値ではなく別の画面へのボタン（像心电图的波形 → 测定）。
  final bool link;
}

